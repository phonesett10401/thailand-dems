// One-off: Natural Earth 1:50m (public domain, via world-atlas) → src/thailand.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import { geoMercator, geoPath } from 'd3-geo';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));
const thailand = feature(topo, topo.objects.countries).features.find((f) => f.id === '764');
if (!thailand) throw new Error('Thailand (764) not found');

const W = 600, H = 1000;
const proj = geoMercator().fitExtent([[20, 20], [W - 20, H - 20]], thailand);
const d = geoPath(proj).digits(1)(thailand);
const at = (lon, lat) => proj([lon, lat]).map((n) => Math.round(n));
const PLACES = {
	chiangmai: at(98.98, 18.79),
	maesot: at(98.57, 16.71),
	ayutthaya: at(100.57, 14.35),
	bangkok: at(100.5, 13.76),
	nakhonsi: at(99.96, 8.43)
};
writeFileSync(
	new URL('../src/thailand.ts', import.meta.url),
	`// Generated by scripts/make-thailand.mjs from Natural Earth 1:50m (public domain). Do not edit.\n` +
		`export const THAI_VIEWBOX = '0 0 ${W} ${H}';\n` +
		`export const THAI_PATH = ${JSON.stringify(d)};\n` +
		`export const PLACES: Record<'chiangmai' | 'maesot' | 'ayutthaya' | 'bangkok' | 'nakhonsi', [number, number]> = ${JSON.stringify(PLACES)};\n`
);
console.log('wrote src/thailand.ts', d.length, 'chars');
